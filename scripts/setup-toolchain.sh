#!/usr/bin/env bash
# Downloads the two jars the APK build needs (apktool + apksigner) into toolchain/
# and prints the environment variables to export. A JDK is still required; if
# `java` is missing, this script tells you what to install.
#
#   bash scripts/setup-toolchain.sh
#   source toolchain/env.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TC="$ROOT/toolchain"
mkdir -p "$TC"

APKTOOL_URL="https://github.com/iBotPeaches/Apktool/releases/download/v2.9.3/apktool_2.9.3.jar"
# apksigner ships inside the build-tools zip; this mirror is a plain jar copy
APKSIGNER_URL="https://raw.githubusercontent.com/fornwall/apksigner/master/apksigner.jar"

fetch() {
  local url="$1" out="$2"
  if [ -s "$out" ]; then
    echo "  have $(basename "$out")"
    return
  fi
  echo "  downloading $(basename "$out")"
  if command -v curl >/dev/null 2>&1; then
    curl -fL --retry 2 -o "$out" "$url"
  else
    wget -q -O "$out" "$url"
  fi
}

echo "==> fetching build tools into $TC"
fetch "$APKTOOL_URL" "$TC/apktool.jar" || echo "  !! could not download apktool — get it from https://github.com/iBotPeaches/Apktool/releases"
fetch "$APKSIGNER_URL" "$TC/apksigner.jar" || echo "  !! could not download apksigner — copy it out of Android build-tools/"

if ! command -v java >/dev/null 2>&1; then
  echo
  echo "!! 'java' not found. Install a JDK 17+ first:"
  echo "   Debian/Ubuntu : sudo apt install openjdk-17-jdk"
  echo "   macOS         : brew install openjdk@17"
  echo "   Termux        : pkg install openjdk-17"
  echo "   then re-run this script."
fi

cat > "$TC/env.sh" <<EOF
# generated by scripts/setup-toolchain.sh
export APKTOOL_JAR="$TC/apktool.jar"
export APKSIGNER_JAR="$TC/apksigner.jar"
export PYTHON="\${PYTHON:-python3}"
# export JAVA_HOME=/path/to/jdk   # uncomment if java is not on PATH
EOF

echo
echo "==> next:"
echo "    source toolchain/env.sh"
echo "    bash scripts/build-apk.sh"
echo
echo "Icons need Pillow:   pip install pillow"
